-- Departamentos de uma instituicao (casos de uso 26 e 27)
CREATE TABLE departamento (
    id_departamento  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj_instituicao VARCHAR(14)  NOT NULL REFERENCES instituicao (cnpj),
    nome             VARCHAR(150) NOT NULL,
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_departamento_nome UNIQUE (cnpj_instituicao, nome)
);

-- Motivo do atendimento (caso de uso 4)
ALTER TABLE atendimento ADD COLUMN motivo VARCHAR(300);

-- Finalidade da solicitacao de acesso (caso de uso 18)
ALTER TABLE solicitacao_acesso ADD COLUMN finalidade VARCHAR(300);

-- Via e frequencia da prescricao (caso de uso 8)
