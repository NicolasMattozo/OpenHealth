-- V1: schema inicial do Sistema de Prontuarios (espelha o modelo ER do grupo)

-- ===== Instituicoes e usuarios =====

CREATE TABLE instituicao (
    cnpj      VARCHAR(14)  PRIMARY KEY,
    nome      VARCHAR(200) NOT NULL,
    endereco  VARCHAR(300),
    ativo     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_instituicao_cnpj CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE usuario (
    id_usuario            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 VARCHAR(200) NOT NULL,
    nome                  VARCHAR(200) NOT NULL,
    senha_hash            VARCHAR(100) NOT NULL,
    administrador_sistema BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo                 BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_usuario_email ON usuario (lower(email));

-- Vinculo do usuario com cada instituicao em que atua
CREATE TABLE usuario_instituicao (
    id_usuario      BIGINT      NOT NULL REFERENCES usuario (id_usuario),
    cnpj_instituicao VARCHAR(14) NOT NULL REFERENCES instituicao (cnpj),
    ativo           BOOLEAN     NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id_usuario, cnpj_instituicao)
);

-- Papeis do usuario dentro de cada instituicao
CREATE TABLE usuario_papel (
    id_usuario       BIGINT      NOT NULL,
    cnpj_instituicao VARCHAR(14) NOT NULL,
    papel            VARCHAR(30) NOT NULL,
    PRIMARY KEY (id_usuario, cnpj_instituicao, papel),
    FOREIGN KEY (id_usuario, cnpj_instituicao)
        REFERENCES usuario_instituicao (id_usuario, cnpj_instituicao),
    CONSTRAINT ck_usuario_papel CHECK (papel IN
        ('RECEPCIONISTA', 'MEDICO', 'ENFERMEIRO', 'ADMIN_INSTITUICAO'))
);

CREATE TABLE paciente (
    cpf              VARCHAR(11) PRIMARY KEY,
    id_usuario       BIGINT      NOT NULL UNIQUE REFERENCES usuario (id_usuario),
    data_nascimento  DATE        NOT NULL,
    CONSTRAINT ck_paciente_cpf CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE prontuario (
    cpf_paciente  VARCHAR(11) PRIMARY KEY REFERENCES paciente (cpf),
    data_abertura DATE        NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE profissional_saude (
    id_usuario     BIGINT       NOT NULL REFERENCES usuario (id_usuario),
    tipo           VARCHAR(20)  NOT NULL,
    numero_conselho VARCHAR(20) NOT NULL,
    uf_conselho    CHAR(2)      NOT NULL,
    especialidade  VARCHAR(100),
    PRIMARY KEY (id_usuario, tipo),
    CONSTRAINT ck_profissional_tipo CHECK (tipo IN ('MEDICO', 'ENFERMEIRO'))
);

-- ===== Acesso aos dados do paciente =====

CREATE TABLE solicitacao_acesso (
    id_solicitacao   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf_paciente     VARCHAR(11) NOT NULL REFERENCES paciente (cpf),
    cnpj_instituicao VARCHAR(14) NOT NULL,
    id_recepcionista BIGINT      NOT NULL,
    data_solicitacao TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_decisao     TIMESTAMPTZ,
    data_revogacao   TIMESTAMPTZ,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    FOREIGN KEY (id_recepcionista, cnpj_instituicao)
        REFERENCES usuario_instituicao (id_usuario, cnpj_instituicao),
    CONSTRAINT ck_solicitacao_status CHECK (status IN
        ('PENDENTE', 'APROVADA', 'NEGADA', 'REVOGADA'))
);
-- No maximo uma solicitacao "viva" por paciente + instituicao
CREATE UNIQUE INDEX uq_solicitacao_ativa
    ON solicitacao_acesso (cpf_paciente, cnpj_instituicao)
    WHERE status IN ('PENDENTE', 'APROVADA');
CREATE INDEX ix_solicitacao_paciente ON solicitacao_acesso (cpf_paciente, status);

-- ===== Atendimento e registros clinicos =====

CREATE TABLE atendimento (
    id_atendimento   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf_paciente     VARCHAR(11) NOT NULL REFERENCES prontuario (cpf_paciente),
    cnpj_instituicao VARCHAR(14) NOT NULL REFERENCES instituicao (cnpj),
    id_solicitacao   BIGINT      REFERENCES solicitacao_acesso (id_solicitacao),
    id_recepcionista BIGINT      NOT NULL,
    id_usuario_medico BIGINT,
    tipo_medico      VARCHAR(20),
    data_hora        TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_finalizacao TIMESTAMPTZ,
    status           VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    FOREIGN KEY (id_recepcionista, cnpj_instituicao)
        REFERENCES usuario_instituicao (id_usuario, cnpj_instituicao),
    FOREIGN KEY (id_usuario_medico, tipo_medico)
        REFERENCES profissional_saude (id_usuario, tipo),
    CONSTRAINT ck_atendimento_medico CHECK (
        (id_usuario_medico IS NULL AND tipo_medico IS NULL)
        OR (id_usuario_medico IS NOT NULL AND tipo_medico IS NOT NULL
            AND tipo_medico = 'MEDICO')),
    CONSTRAINT ck_atendimento_status CHECK (status IN
        ('ABERTO', 'EM_ANDAMENTO', 'FINALIZADO', 'CANCELADO'))
);
CREATE INDEX ix_atendimento_paciente    ON atendimento (cpf_paciente, data_hora DESC);
CREATE INDEX ix_atendimento_instituicao ON atendimento (cnpj_instituicao, status);

-- Tabela-base dos registros; "tipo" e o discriminador das tabelas filhas
CREATE TABLE registro_clinico (
    id_registro             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atendimento          BIGINT      NOT NULL REFERENCES atendimento (id_atendimento),
    id_usuario_autor        BIGINT      NOT NULL,
    tipo_profissional_autor VARCHAR(20) NOT NULL,
    data_registro           TIMESTAMPTZ NOT NULL DEFAULT now(),
    visivel_ao_paciente     BOOLEAN     NOT NULL DEFAULT FALSE,
    tipo                    VARCHAR(30) NOT NULL,
    FOREIGN KEY (id_usuario_autor, tipo_profissional_autor)
        REFERENCES profissional_saude (id_usuario, tipo),
    CONSTRAINT ck_registro_tipo CHECK (tipo IN
        ('TRIAGEM', 'DADO_CLINICO', 'CONDICAO_DIAGNOSTICO',
         'REQUISICAO_EXAME', 'PRESCRICAO_MEDICAMENTO'))
);
CREATE INDEX ix_registro_atendimento ON registro_clinico (id_atendimento);

CREATE TABLE triagem (
    id_registro         BIGINT PRIMARY KEY REFERENCES registro_clinico (id_registro),
    classificacao_risco VARCHAR(30) NOT NULL,
    sintomas            TEXT
);

CREATE TABLE dado_clinico (
    id_registro BIGINT PRIMARY KEY REFERENCES registro_clinico (id_registro),
    tipo        VARCHAR(60)  NOT NULL,
    valor       VARCHAR(500) NOT NULL
);

CREATE TABLE condicao_diagnostico (
    id_registro BIGINT PRIMARY KEY REFERENCES registro_clinico (id_registro),
    descricao   TEXT        NOT NULL,
    cid         VARCHAR(10)
);

CREATE TABLE prescricao_medicamento (
    id_registro BIGINT PRIMARY KEY REFERENCES registro_clinico (id_registro),
    medicamento VARCHAR(200) NOT NULL,
    dosagem     VARCHAR(100) NOT NULL
);

CREATE TABLE requisicao_exame (
    id_registro BIGINT PRIMARY KEY REFERENCES registro_clinico (id_registro),
    tipo_exame  VARCHAR(200) NOT NULL
);

-- Resultados versionados: corrigir um resultado cria uma nova versao
CREATE TABLE resultado_exame (
    id_requisicao                  BIGINT      NOT NULL REFERENCES requisicao_exame (id_registro),
    versao                         INTEGER     NOT NULL,
    resultado                      TEXT        NOT NULL,
    data_resultado                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    id_usuario_registrador         BIGINT      NOT NULL,
    tipo_profissional_registrador  VARCHAR(20) NOT NULL,
    PRIMARY KEY (id_requisicao, versao),
    FOREIGN KEY (id_usuario_registrador, tipo_profissional_registrador)
        REFERENCES profissional_saude (id_usuario, tipo),
    CONSTRAINT ck_resultado_versao CHECK (versao >= 1)
);

-- ===== Auditoria =====

CREATE TABLE log_auditoria (
    id_log        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    BIGINT      REFERENCES usuario (id_usuario),
    instante      TIMESTAMPTZ NOT NULL DEFAULT now(),
    acao          VARCHAR(60) NOT NULL,
    tipo_recurso  VARCHAR(60) NOT NULL,
    chave_recurso JSONB
);
CREATE INDEX ix_log_usuario ON log_auditoria (id_usuario, instante DESC);